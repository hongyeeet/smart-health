#!/usr/bin/env python3
"""Assemble the demo patient "Mr Tan" (E1-4 step 9). Safe to run twice (same seed, same end date, same data).

Needs import_cgmacros.py and seed_reference.py to have run first (his real data and the drug list).
It loads the simulated history from simulate_persona.py, fills his profile extras (diagnosis year, placeholder
targets, onboarding), and writes data/demo/DISCLOSURE.md: the list of everything that is simulated.

Usage: python scripts/seed_demo.py
"""
import json
import sys
from datetime import datetime, time, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import simulate_persona as sim  # noqa: E402
from etl_common import DEMO_DIR, bulk_insert, connect, count, demo_end_date, local_to_utc, report, uid  # noqa: E402

COLS = {
    "patient_medications": ["id", "user_id", "drug_reference_id", "display_name", "kind", "strength", "dose_amount", "dose_unit", "times_per_day", "schedule_times", "with_food", "window_minutes", "start_on", "status", "source", "confirmed_by_user_at"],
    "medication_ingredients": ["id", "patient_medication_id", "ingredient_name", "source"],
    "dose_events": ["id", "user_id", "patient_medication_id", "scheduled_at", "window_end_at", "status", "confirmed_at", "miss_reason", "reason_captured_at"],
    "glucose_readings": ["id", "user_id", "measured_at", "value_mmol", "context", "source", "external_id", "device", "quality_ok"],
    "mood_checkins": ["id", "user_id", "checked_on", "mood", "stress", "sleep_quality", "energy"],
    "sleep_sessions": ["id", "user_id", "start_at", "end_at", "asleep_min", "awake_min", "efficiency_pct", "source", "external_id"],
    "health_samples": ["id", "user_id", "metric", "start_at", "end_at", "value", "unit", "source", "device", "external_id"],
    "workouts": ["id", "user_id", "started_at", "duration_s", "activity", "intensity", "avg_hr", "source", "external_id"],
    "blood_pressure_readings": ["id", "user_id", "measured_at", "systolic", "diastolic", "pulse", "context", "source", "external_id"],
    "symptom_checkins": ["id", "user_id", "question_key", "asked_at", "answered_at", "answer", "skipped"],
    "symptom_logs": ["id", "user_id", "occurred_at", "symptom", "severity", "source", "checkin_id"],
    "lab_results": ["id", "user_id", "kind", "value", "unit", "taken_on", "source", "external_id"],
    "body_measurements": ["id", "user_id", "measured_at", "weight_kg", "source", "external_id"],
    "meals": ["id", "user_id", "eaten_at", "meal_type", "description", "source"],
    "meal_items": ["id", "meal_id", "custom_name", "portion_multiplier", "carbs_g", "kcal", "protein_g", "fat_g", "fibre_g", "estimated_by", "evidence_status"],
    "conditions": ["id", "user_id", "name", "since_year"],
    "family_history": ["id", "user_id", "relation", "condition"],
    "consents": ["id", "user_id", "kind", "version", "granted_at"],
    "appointments": ["id", "user_id", "kind", "status", "scheduled_for", "location", "suggested_reason", "confirmed_by_user_at"],
    "patient_preventive_status": ["user_id", "preventive_item_id", "last_done_on", "next_due_on", "status"],
    "devices": ["id", "user_id", "kind", "label", "source", "last_synced_at", "status"],
    "health_goals": ["id", "user_id", "kind", "target_value", "unit", "set_by", "active"],
}
ORDER = ["patient_medications", "medication_ingredients", "dose_events", "glucose_readings", "mood_checkins", "sleep_sessions", "health_samples", "workouts",
         "blood_pressure_readings", "symptom_checkins", "symptom_logs", "lab_results", "body_measurements", "meals", "meal_items", "conditions",
         "family_history", "consents", "appointments", "patient_preventive_status", "devices", "health_goals"]


def write_disclosure(end_date, disc, counts):
    lines = ["# Disclosure: simulated demo data", "",
             "Generated by `scripts/seed_demo.py`. **Do not edit by hand.** The demo patient \"Mr Tan\" is CGMacros participant 046 (a real person in a public dataset, "
             "anonymous, dates shifted). His real glucose, heart rate, meals and labs are loaded as they are. Everything below is **simulated** because no cited dataset "
             "has it, using a fixed seed so the data is identical every time. It is built only from cited data and the persona in `docs/mockup/mockup-prompt.md`, "
             "and must be disclosed as simulated (prd.md A8).", "",
             f"- Demo end date: **{end_date}** (the last real sensor day). Simulated window: the 60 days ending on it. Seed: {sim.SEED}.",
             "- Where a table has a source column, simulated rows use `source`/`entry_source = demo_dataset` and an `external_id` starting `sim:`.",
             "- Doses, mood check-ins, symptoms, check-in questions, appointments, conditions, family history, consents, goals and preventive status have no source column; "
             "every row of the demo user (`users.is_demo`, key `cgmacros-046`) in those tables is simulated.", "",
             "| Table | Rows loaded | From | To | Rule |", "|---|---|---|---|---|"]
    for d in disc:
        lines.append(f"| {d['table']} | {d['rows']:,} | {d['from']} | {d['to']} | {d['rule']} |")
    lines += ["", "## Real data in the same patient (not simulated)", "",
              "Glucose from two sensors (Libre Pro, Dexcom G6) for about 10 days, watch heart rate and active energy, 29 meals with measured macros, and the lab values "
              "and body weight from `bio.csv`. The last 3 hours are held back for the replay tool and stream in as `entry_source = replay`.", "",
              "## Row counts for the demo patient now", "", "| Table | Rows |", "|---|---|"]
    lines += [f"| {t} | {n:,} |" for t, n in counts.items()]
    (DEMO_DIR / "DISCLOSURE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    end_date = demo_end_date()
    U = uid("user", sim.USER_KEY)
    with connect() as conn:
        if not conn.execute("select 1 from users where id = %s", (U,)).fetchone():
            raise SystemExit("Run scripts/import_cgmacros.py first (the demo patient's real data).")
        now = conn.execute("select max(measured_at at time zone 'Asia/Singapore') from glucose_readings where user_id = %s and device = 'libre_pro'", (U,)).fetchone()[0]
        real = conn.execute("""select m.meal_type, i.carbs_g::float, i.kcal::float, i.protein_g::float, i.fat_g::float, i.fibre_g::float
                               from meals m join meal_items i on i.meal_id = m.id
                               where m.user_id = %s and m.description like 'CGMacros dataset meal%%' order by m.eaten_at""", (U,)).fetchall()
        morning = conn.execute("""select avg(value_mmol)::float from glucose_readings where user_id = %s and device = 'libre_pro'
                                  and extract(hour from measured_at at time zone 'Asia/Singapore') = 7""", (U,)).fetchone()[0]
        rows, disc = sim.build(end_date, now, real, real_morning_mean=round(morning or 7.4, 1))
        for t in ORDER:
            n = bulk_insert(conn, t, COLS[t], rows[t])
            print(f"  {t}: inserted {n:,} of {len(rows[t]):,}")
        # profile extras: updates are idempotent (same values every run)
        conn.execute("""update patient_profiles set diagnosed_year = %s, smoker = false, onboarding_method = 'form',
                        targets = %s::jsonb where user_id = %s""",
                     (end_date.year - 6, json.dumps({"fasting": [4.0, 7.0], "post_meal_max": 10.0, "hba1c_max": 7.0,
                                                    "source": "team placeholder: clinical review pending"}), U))
        conn.execute("update users set onboarding_completed_at = %s where id = %s", (local_to_utc(datetime.combine(end_date - timedelta(days=sim.WINDOW_DAYS), time(9, 0))), U))
        conn.commit()
        counts = {t: count(conn, t, "user_id = %s", (U,)) for t in ("patient_medications", "dose_events", "glucose_readings", "health_samples", "meals", "mood_checkins", "sleep_sessions", "workouts", "blood_pressure_readings", "symptom_logs", "lab_results", "body_measurements", "appointments", "devices", "health_goals")}
        write_disclosure(end_date, disc, counts)
        report("demo patient", **{k: v for k, v in counts.items()})
        print("database size:", conn.execute("select pg_size_pretty(pg_database_size(current_database()))").fetchone()[0], "| disclosure: data/demo/DISCLOSURE.md")


if __name__ == "__main__":
    main()
